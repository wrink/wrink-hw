"""Command line interface: ``populate-jlc-library <project|schematic|dir> [options]``."""
from __future__ import annotations

import argparse
import importlib.util
import os
import logging
import re
import sys
from pathlib import Path
from typing import List, Optional

from . import __version__
from .downloader import ENV_COMMAND, Downloader
from .library import populate
from .project import InputError, register_library, resolve
from .schematic import DEFAULT_FIELDS, collect_parts

def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="populate-jlc-library",
        description="Download the JLCPCB/EasyEDA footprints (and 3D models) of every LCSC part used in a "
                    "KiCad schematic into a local footprint library you can check in.",
    )
    p.add_argument("input", type=Path, help="a .kicad_pro, a .kicad_sch (hierarchical sheets are followed), "
                                            "or a directory containing one project")
    p.add_argument("-o", "--out", type=Path, help="output directory (default: <project dir>/jlcpcb-lib)")
    p.add_argument("--lib-name", default="jlcpcb", help="library nickname / .pretty name (default: jlcpcb)")
    p.add_argument("--field", action="append", dest="fields", metavar="NAME",
                   help="extra symbol field holding the LCSC number (repeatable; defaults: "
                        + ", ".join(DEFAULT_FIELDS) + ")")
    p.add_argument("--only", help="comma separated LCSC numbers; skip all others")
    p.add_argument("--skip-dnp", action="store_true", help="skip parts that are do-not-populate everywhere")
    p.add_argument("--full", action="store_true", help="also generate symbols (<lib>.kicad_sym)")
    p.add_argument("--overwrite", action="store_true", help="regenerate footprints already in the library")
    p.add_argument("--register", action="store_true",
                   help="add the library to the project's fp-lib-table (restart KiCad afterwards)")
    p.add_argument("--dry-run", action="store_true", help="list the parts found; download nothing")
    p.add_argument("--delay", type=float, default=0.5, help="seconds between downloads (default 0.5)")
    p.add_argument("--timeout", type=float, default=90.0, help="per-download timeout in seconds")
    p.add_argument("-v", "--verbose", action="store_true")
    p.add_argument("--version", action="version", version=f"%(prog)s {__version__}")
    return p


def main(argv: Optional[List[str]] = None) -> int:
    args = build_parser().parse_args(argv)
    if not re.fullmatch(r"[A-Za-z0-9_-]+", args.lib_name):
        print("error: --lib-name may only contain letters, digits, '_' and '-'", file=sys.stderr)
        return 2
    logging.basicConfig(level=logging.DEBUG if args.verbose else logging.WARNING, format="%(levelname)s: %(message)s")

    try:
        target = resolve(args.input)
    except InputError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    fields = list(DEFAULT_FIELDS) + (args.fields or [])
    coll = collect_parts(target.root_schematic, fields)
    only = {x.strip().upper() for x in (args.only or "").split(",") if x.strip()}
    parts = [p for _, p in sorted(coll.parts.items(), key=lambda kv: int(kv[0][1:]))]
    if only:
        missing = only - {p.lcsc for p in parts}
        if missing:
            print(f"warning: not in the schematic: {', '.join(sorted(missing))}", file=sys.stderr)
        parts = [p for p in parts if p.lcsc in only]
    if args.skip_dnp:
        parts = [p for p in parts if not p.dnp_everywhere]

    print(f"{target.root_schematic.name}: {len(coll.sheets)} sheet(s), {len(parts)} distinct LCSC part(s)")
    for p in parts:
        flag = "  [DNP]" if p.dnp_everywhere else ""
        print(f"  {p.lcsc:<10} {', '.join(p.sorted_refs()):<34} {'; '.join(sorted(p.values))}{flag}")
    if coll.without_lcsc:
        print(f"  note: {len(coll.without_lcsc)} part(s) have no LCSC number: {', '.join(coll.without_lcsc)}")
    if args.dry_run or not parts:
        return 0

    if not os.environ.get(ENV_COMMAND) and importlib.util.find_spec("easyeda2kicad") is None:
        print("error: easyeda2kicad is not installed in this Python environment "
              "(pip install easyeda2kicad, or reinstall this package with its dependencies)", file=sys.stderr)
        return 2

    out = (args.out or target.project_dir / "jlcpcb-lib").resolve()
    dl = Downloader(out, args.lib_name, full=args.full, overwrite=args.overwrite, timeout=args.timeout,
                    project_dir=target.project_dir)
    print(f"downloading into {out}")
    results = populate(parts, dl, delay=args.delay)

    if args.register:
        state = register_library(target.project_dir, args.lib_name, dl.pretty_dir,
                                 "JLCPCB/EasyEDA footprints (generated by populate-jlc-library)")
        print(f"fp-lib-table: {args.lib_name} {state}" + (" (restart KiCad)" if state != "present" else ""))

    failed = [r.lcsc for _, r in results if r.status == "failed"]
    print(f"done: {len(results) - len(failed)} ok, {len(failed)} failed; map: {out / 'lcsc_footprints.csv'}")
    if failed:
        print(f"failed: {', '.join(failed)} (see {out / 'download.log'})", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
